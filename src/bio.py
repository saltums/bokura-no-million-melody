    if not C: return
    ok = _meet(C)
    moved = bool(re.search(r"上京(し|後|して|した|すると|先)", txt))  # 上京してから結成: 結成は東京、出身は地方
    if moved:
        ok_h = _meet([[x for x in ALLC if _pc(x)[0] != "東京都"]] + [c for c in C if not all(_pc(x)[0] == "東京都" for x in c)])
        ok_f = [x for x in ALLC if x.startswith("東京都")]
    else:
        ok_h = ok_f = ok
