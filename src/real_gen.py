def R(seen, key, tr):
    y, ti, kind, o, lb, th, pr = T[key]
    return rel(seen, y, o, kind, ti, lb, tr, th, pr)


def X(c, ok, tx, mb=None):
    d = {"t": "x", "c": c, "ok": ok, "tx": tx}
    if mb: d["mb"] = mb
    return d


def ev(tx, mb=None):
    d = {"t": "e", "tx": tx}
    if mb: d["mb"] = mb
    return d


