def wk(w):
    return {"y": w["y"], "ti": w["ti"], "tr": w["tr"], "th": w["th"], "pr": w["pr"], "o": w["o"]}


def ending(a, b, c, d):
    if (a, b, c, d) == (0, 0, 0, 0):
        return "四人から三人になっても、青春を鳴らし続けた。結成から20年を超えてなお、二周目の青春を歌うバンドとして愛されている"
    if c == 1 and d == 0:
        return "四人に戻ったバンドは、新しい音を足しながら続いた。昔の聴き手と新しい聴き手が、同じ客席に並んでいる"
    if b == 1 and a == 0:
        return "売れ線に寄せた時期の大ヒットは、いまもカラオケで歌われる。バンドは形を変えながら、静かに続いている"
    if a == 1:
        return "インディーズのまま、自分たちの場所を守り続けた。大きな名前にはならなくても、客席の顔はみんな覚えている"
    if d == 1:
        return "四人時代の音を磨き続けた。流行とは別の場所で、変わらない音として信頼されている"
    return "形を変えながら、青春を鳴らし続けた。ファンにとっては、自分の人生の一部になっている"
