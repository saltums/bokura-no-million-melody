def rel(seen, y, o, kind, ti, lb, tr, theme, pr):
    h = dict(kind=kind, ord="", title=ti, year=y, tier=tr, theme=theme, premise=pr, label=lb)
    tk = tracks.tracklist(h, "band", 2, theme, list(seen)); seen.append(ti)
    lyrics.VG = "m"
    ly = lyrics_struct.make_struct(theme, "ギターロック", pr, ti, y, WORDS, False, 2)
    if ly: ly["vg"] = "m"
    rs = (HIT if tr >= 2 else FLOP)[(y + len(ti)) % (len(HIT) if tr >= 2 else len(FLOP))]
    fm = FORM[(y * 3 + len(ti)) % len(FORM)]
    return {"t": "r", "y": y, "o": o, "ti": ti, "lb": lb, "tr": tr, "pr": pr, "th": theme, "rs": rs, "fm": fm, "tk": tk, "ly": ly}


