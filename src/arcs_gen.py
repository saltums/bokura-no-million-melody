def pr_of(r, th):
    t = THEME[th]; return r.choice(t["pre"]).format(time=r.choice(g.TIME), place=r.choice(g.PLACE), thing=r.choice(g.THING))


def rel(a, seen, pos, y, tier, th, lb, dev):
    r = random.Random(H(a["k"], "rel", pos, dev))
    pool = PT[a["par"]]; ti = pool[(pos + dev * 2) % len(pool)]
    while ti in seen: ti = pool[(pool.index(ti) + 1) % len(pool)]
    seen.append(ti)
    pr = pr_of(r, th)
    h = dict(kind=KIND[pos], ord="", title=ti, year=y, tier=tier, theme=th, premise=pr, label=lb)
    tk = tracks.tracklist(h, a["st"] if a["st"] in ("band", "duo", "rap", "solo", "beat") else "band", era_of(a["y0"]), th, list(seen))
    lyrics.VG = a["vg"]
    ly = lyrics_struct.make_struct(th, a["ge"], pr, ti, y, WORDS, era_of(a["y0"]) <= 1, era_of(a["y0"]))
    if ly: ly["vg"] = a["vg"]
    t = THEME[th]; rs = r.choice(t["hit"] if tier >= 2 else t["flop"]) if tier >= 2 else r.choice(FLOP)
    return {"t": "r", "y": y, "o": ORD[pos], "ti": ti, "lb": lb, "tr": tier, "pr": pr, "th": th, "rs": rs if tier < 2 else r.choice(HIT), "fm": r.choice(FORM), "tk": tk, "ly": ly}


