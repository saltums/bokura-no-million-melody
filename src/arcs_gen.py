def build(a, i):
    st = a["st"]; seed = 96000 + i
    mm = tracks.people(seed, st if st != "beat" else "beat")
    for j, m_ in enumerate(mm[:len(a["roles"])] if a["roles"] else []):
        m_["r"] = a["roles"][j]; m_["t"] = a["tr"][j] if j < len(a["tr"]) else m_["t"]
    if a["roles"]:
        mm = mm[:len(a["roles"])]
        while len(mm) < len(a["roles"]):
            nw = tracks.newcomer(seed, a["roles"][len(mm)], {x["n"] for x in mm}); nw["r"] = a["roles"][len(mm)]; nw["t"] = a["tr"][len(mm)] if len(mm) < len(a["tr"]) else nw.get("t", ""); mm.append(nw)
    import roster as _ro
    mm = _ro.apply(a, mm, seed)
    m = meta(a, mm, i); th = a["th"]; seen = []
    def stage_rels(si, dev_eff, dev):
        out = []; cv = a["cv"][si]
        base_pos = [0, 2, 4, 5][si]
        for k, bt in enumerate(cv):
            pos = base_pos + k if si < 2 else base_pos
            if si == 0: pos = k
            y = a["y0"] + a["yr"][min(pos, len(a["yr"]) - 1)]
            lb = a["lb"][si]
            out.append(rel(a, seen_ref[0], pos, y, cl(bt + dev_eff), th[(pos + dev) % len(th)], lb, dev))
        return out
    seen_ref = [seen]
    # 開幕
    s0 = [{"t": "e", "tx": a["ev"][0]}] + stage_rels(0, 0, 0)
    d1, d2, d3 = a["d"]
    def q(d): return {"prompt": d[0], "labels": [d[1], d[2]], "h": 0}
    def X(d, alt):
        return {"t": "x", "c": d[2] if alt else d[1], "ok": (d[6] if alt else d[5]) >= 0, "tx": d[4] if alt else d[3]}
    kids = []
    for x1 in (0, 1):
        seen1 = copy.deepcopy(seen); seen_ref[0] = seen1
        seg1 = [X(d1, x1), {"t": "e", "tx": a["ev"][1]}] + stage_rels(1, d1[6 if x1 else 5], x1)
        k2 = []
        for x2 in (0, 1):
            seen2 = copy.deepcopy(seen1); seen_ref[0] = seen2
            eff = d1[6 if x1 else 5] + d2[6 if x2 else 5]
            seg2 = [X(d2, x2), {"t": "e", "tx": a["ev"][2]}] + stage_rels(2, eff, x1 + x2)
            k3 = []
            for x3 in (0, 1):
                seen3 = copy.deepcopy(seen2); seen_ref[0] = seen3
                eff3 = eff + d3[6 if x3 else 5]
                seg3 = [X(d3, x3), {"t": "e", "tx": a["ev"][3]}] + stage_rels(3, eff3, x1 + x2 + x3)
                works = [w for w in s0 + seg1 + seg2 + seg3 if w["t"] == "r"]
                dv = x1 + x2 + x3
                tx = a["eh"] if dv == 0 else a["ea"][min(dv - 1, len(a["ea"]) - 1)]
                k3.append({"s": seg3, "e": {"tx": tx.rstrip("。"), "w": [wk(w) for w in works], "mm": mm}})
            k2.append({"s": seg2, "q": q(d3), "n": k3})
        kids.append({"s": seg1, "q": q(d2), "n": k2})
    return {"m": m, "t": {"s": s0, "q": q(d1), "n": kids}}


def build_all():
    return [build(a, i) for i, a in enumerate(ARCS)]
