import re as _re
# 語ごとの例外(別の意味の語を巻き込まない)
_PAT = {
    "ネット": r"(?<![ァ-ヴー])ネット(?!ワーク)|インターネット", "メール": r"(?<![ァ-ヴー])メール", "通知": r"通知(?!表)", "推し": r"推し(?=[のがにをへとも活メ]|$)",
    "バズ": r"バズ(?!ー)", "アプリ": r"アプリ(?!コ)", "配信": r"(?<!新聞)配信", "LINE": r"LINE(?=[ぁ-んァ-ヴ一-龥])", "マウント": r"マウント(?=[をがとの]|取)",
    "携帯": r"携帯(?![用品食性ラ])", "拡散": r"拡散(?=[しさすされ希])", "動画": r"動画(?!家)",
}
_RX = {}
for _w in WORD_YEAR:
    if _w in _PAT: _RX[_w] = _re.compile(_PAT[_w])
    elif _re.fullmatch(r"[A-Za-z0-9\-]+", _w): _RX[_w] = _re.compile(r"(?<![A-Za-z])" + _re.escape(_w) + r"(?![A-Za-z])")
    else: _RX[_w] = None
WORD_YEAR.setdefault("携帯", 1995)
_RX.setdefault("携帯", _re.compile(_PAT["携帯"]))


_MAXY = max(WORD_YEAR.values())
_ANY = _re.compile("|".join(_re.escape(w) for w in sorted(WORD_YEAR, key=len, reverse=True)))
_CACHE = {}


def _present(text):
    """text に含まれる時代語 [(語, 年)](文字列ごとにキャッシュ。生成で同じ文を何万回も見るため)"""
    r = _CACHE.get(text)
    if r is None:
        r = []
        if _ANY.search(text):
            for w, y in WORD_YEAR.items():
                if w[0] not in text: continue
                rx = _RX.get(w)
                if (rx.search(text) if rx else w in text): r.append((w, y))
        r = tuple(r)
        if len(_CACHE) < 300000: _CACHE[text] = r
    return r


def bad_words(text, year):
    """year の時点でまだ無い言葉のリスト"""
    if not text or year is None or year >= _MAXY:
        return []
    return [w for w, y in _present(text) if year < y]


def ok(text, year):
    return not bad_words(text, year)


def filt(items, year):
    """文字列リストから時代違いを除く(全部消えたら元を返す)"""
    out = [z for z in items if ok(z, year)]
    return out or list(items)
